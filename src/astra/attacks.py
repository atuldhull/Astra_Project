"""Attack timeline → ArduPilot Lua script.

Why Lua inside the simulator instead of an external MAVLink injector:
the script runs on the simulator's own clock, so attack timing is identical
at 1x or 10x speed-up and doesn't depend on host scheduling. The script only
writes SIM_GPS1_* parameters, which belong to the *simulated GPS sensor*,
never to the autopilot code under test. It also logs the true attack state
to the dataflash log (message ASTK) so every flight is self-labelled for the
forensics engine.

Effects composed per 50 ms tick (later attacks in the list override
earlier ones on the same channel):
  jam_denial        SIM_GPS1_ENABLE=0  (no lock)
  jam_intermittent  ENABLE toggled with duty cycle
  jam_chaotic       SIM_GPS1_JAM=1     (ArduPilot's own jamming model)
  jam_degrade       NUMSATS, ACC
  spoof_jump        GLTCH_X/Y step (deg)
  spoof_drag        GLTCH_X/Y ramp (deg) + SPFV_X/Y velocity bias (ASTRA patch)
  meaconing         LAG_MS
"""

from __future__ import annotations

import math

from astra.scenario import (
    JamChaotic, JamDegrade, JamDenial, JamIntermittent, Meaconing, Scenario, SpoofDrag, SpoofJump,
)

M_PER_DEG_LAT = 111319.49079327357  # matches ArduPilot LATLON_TO_M (1e7 scaling removed)

MODEL_CODE = {
    "jam_denial": 1, "jam_intermittent": 2, "jam_chaotic": 3, "jam_degrade": 4,
    "spoof_jump": 5, "spoof_drag": 6, "meaconing": 7,
}


def _lua_num(x: float | int | None) -> str:
    if x is None:
        return "nil"
    if isinstance(x, bool):
        return "1" if x else "0"
    if isinstance(x, int):
        return str(x)
    if not math.isfinite(x):
        raise ValueError("non-finite value in attack spec")
    return repr(float(x))


def _attack_row(a) -> str:
    f = {
        "code": MODEL_CODE[a.model],
        "arm_s": a.start.after_arm_s,
        "wp": a.start.at_waypoint,
        "delay_s": a.start.delay_s,
        "dur_s": a.duration_s,
        "p1": None, "p2": None, "p3": None, "p4": None,
    }
    if isinstance(a, JamIntermittent):
        f.update(p1=a.period_s, p2=a.duty)
    elif isinstance(a, JamDegrade):
        f.update(p1=a.num_sats, p2=a.accuracy_m)
    elif isinstance(a, SpoofJump):
        f.update(p1=a.north_m, p2=a.east_m)
    elif isinstance(a, SpoofDrag):
        f.update(p1=a.rate_ms, p2=a.bearing_deg, p3=a.consistent, p4=a.hold_after_s)
    elif isinstance(a, Meaconing):
        f.update(p1=a.delay_ms)
    elif isinstance(a, (JamDenial, JamChaotic)):
        pass
    else:  # pragma: no cover - schema makes this unreachable
        raise TypeError(a)
    return "  {" + ", ".join(f"{k}={_lua_num(v)}" for k, v in f.items()) + "},"


def lua_script(sc: Scenario) -> str:
    """Return the Lua attack script for a scenario. Deterministic for a given scenario."""
    rows = "\n".join(_attack_row(a) for a in sc.attacks)
    m_per_deg_lon = M_PER_DEG_LAT * math.cos(math.radians(sc.home.lat))
    return _TEMPLATE.format(
        scenario_id=sc.id,
        scenario_hash=sc.content_hash(),
        rows=rows,
        m_per_deg_lat=repr(M_PER_DEG_LAT),
        m_per_deg_lon=repr(m_per_deg_lon),
    )


# Mission index convention (ArduPilot): 0 = home, 1 = takeoff, 2.. = waypoints.
# "at_waypoint = k" starts when waypoint k becomes the active navigation target.
_TEMPLATE = """-- Generated by ASTRA Proving Ground. Do not edit.
-- scenario: {scenario_id}
-- scenario_sha256: {scenario_hash}
-- Writes only SIM_GPS1_* (simulated sensor) parameters.

local ATTACKS = {{
{rows}
}}
local M_PER_DEG_LAT = {m_per_deg_lat}
local M_PER_DEG_LON = {m_per_deg_lon}
local PERIOD_MS = 50

local P = {{
  enable = Parameter("SIM_GPS1_ENABLE"),
  jam    = Parameter("SIM_GPS1_JAM"),
  sats   = Parameter("SIM_GPS1_NUMSATS"),
  acc    = Parameter("SIM_GPS1_ACC"),
  lag    = Parameter("SIM_GPS1_LAG_MS"),
  gx     = Parameter("SIM_GPS1_GLTCH_X"),
  gy     = Parameter("SIM_GPS1_GLTCH_Y"),
  vx     = Parameter("SIM_GPS1_SPFV_X"),
  vy     = Parameter("SIM_GPS1_SPFV_Y"),
}}
local BASE = {{}}
for k, p in pairs(P) do BASE[k] = p:get() end

local arm_ms = nil
local wp_ms = {{}}
local last = {{}}

local function start_ms(a)
  if a.arm_s ~= nil then
    if arm_ms == nil then return nil end
    return arm_ms + (a.arm_s + a.delay_s) * 1000
  end
  local t = wp_ms[a.wp]
  if t == nil then return nil end
  return t + a.delay_s * 1000
end

local function put(k, v)
  if last[k] ~= v then
    P[k]:set(v)
    last[k] = v
  end
end

function update()
  local now = millis():tofloat()
  if arm_ms == nil and arming:is_armed() then arm_ms = now end
  local idx = mission:get_current_nav_index()
  if arm_ms ~= nil and idx ~= nil and idx >= 2 then
    local k = idx - 1
    if wp_ms[k] == nil then wp_ms[k] = now end
  end

  local v = {{}}
  for k, b in pairs(BASE) do v[k] = b end
  local active, code = 0, 0
  local off_n, off_e = 0.0, 0.0

  for _, a in ipairs(ATTACKS) do
    local s = start_ms(a)
    if s ~= nil and now >= s and now < s + a.dur_s * 1000 then
      local t = (now - s) / 1000.0
      active = active + 1
      code = a.code
      if a.code == 1 then
        v.enable = 0
      elseif a.code == 2 then
        local phase = math.fmod(t, a.p1) / a.p1
        if phase < a.p2 then v.enable = 0 end
      elseif a.code == 3 then
        v.jam = 1
      elseif a.code == 4 then
        v.sats = a.p1
        v.acc = a.p2
      elseif a.code == 5 then
        off_n, off_e = a.p1, a.p2
      elseif a.code == 6 then
        local tt = t
        local growing = true
        if a.p4 ~= nil and t > a.p4 then tt = a.p4; growing = false end
        local brg = math.rad(a.p2)
        off_n = a.p1 * tt * math.cos(brg)
        off_e = a.p1 * tt * math.sin(brg)
        if a.p3 == 1 and growing then
          v.vx = a.p1 * math.cos(brg)
          v.vy = a.p1 * math.sin(brg)
        end
      elseif a.code == 7 then
        v.lag = a.p1
      end
    end
  end
  v.gx = BASE.gx + off_n / M_PER_DEG_LAT
  v.gy = BASE.gy + off_e / M_PER_DEG_LON

  for k, _ in pairs(P) do put(k, v[k]) end

  -- Ground-truth attack label in the dataflash log.
  logger:write("ASTK", "Act,Code,OfsN,OfsE,VbN,VbE,En,Jam", "BBffffBB",
    active, code, off_n, off_e, v.vx, v.vy, v.enable, v.jam)
  return update, PERIOD_MS
end

gcs:send_text(6, "ASTRA attack script loaded: {scenario_id}")
return update, PERIOD_MS
"""
